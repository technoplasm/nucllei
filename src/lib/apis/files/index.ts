// llens(#69): ファイル管理ページ用のページング一覧。
// 返却は {"items": [FileModel(data は status のみ・content 無し)], "total": n}。
// user_ids は admin 専用フィルタ(非 admin が渡すと 403)。
type FileListOptions = {
	limit?: number;
	offset?: number;
	order_by?: 'created_at' | 'accessed_at';
	direction?: 'desc' | 'asc';
	user_ids?: string[];
	filename?: string;
};

export const getFileList = async (token: string, options: FileListOptions = {}) => {
	let error = null;

	const searchParams = new URLSearchParams();
	if (options.limit != null) {
		searchParams.append('limit', `${options.limit}`);
	}
	if (options.offset != null) {
		searchParams.append('offset', `${options.offset}`);
	}
	if (options.order_by) {
		searchParams.append('order_by', options.order_by);
	}
	if (options.direction) {
		searchParams.append('direction', options.direction);
	}
	if ((options.user_ids ?? []).length > 0) {
		searchParams.append('user_ids', options.user_ids.join(','));
	}
	if (options.filename) {
		searchParams.append('filename', options.filename);
	}

	const res = await fetch(`${WEBUI_API_BASE_URL}/files/list?${searchParams.toString()}`, {
		method: 'GET',
		headers: {
			Accept: 'application/json',
			'Content-Type': 'application/json',
			authorization: `Bearer ${token}`
		}
	})
		.then(async (res) => {
			if (!res.ok) throw await res.json();
			return res.json();
		})
		.catch((err) => {
			error = err.detail;
			console.log(err);
			return null;
		});

	if (error) {
		throw error;
	}

	return res;
};

