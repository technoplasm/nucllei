import { WEBUI_API_BASE_URL } from '$lib/constants';

// Skill は Prompt の後継(issue #35)。command はバックエンドで先頭 `/` なしに
// 正規化されるため、prompts クライアントのような `/` 前置は行わない。
export type SkillItem = {
	command: string;
	title: string;
	description?: string | null;
	content: string;
	tool_ids?: string[];
	access_control?: null | object;
};

export const createNewSkill = async (token: string, skill: SkillItem) => {
	let error = null;

	const res = await fetch(`${WEBUI_API_BASE_URL}/skills/create`, {
		method: 'POST',
		headers: {
			Accept: 'application/json',
			'Content-Type': 'application/json',
			authorization: `Bearer ${token}`
		},
		body: JSON.stringify(skill)
	})
		.then(async (res) => {
			if (!res.ok) throw await res.json();
			return res.json();
		})
		.catch((err) => {
			error = err.detail;
			console.log(err);
			return null;
		});

	if (error) {
		throw error;
	}

	return res;
};

