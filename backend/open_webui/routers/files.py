@router.post("/", response_model=FileModelResponse)
async def upload_file(
    request: Request,
    file: UploadFile = File(...),
    user=Depends(get_verified_user),
    file_metadata: dict = {},
    process: bool = Query(True),
    model_id: Optional[str] = Query(None),
):
    log.info(f"file.content_type: {file.content_type}")
    try:
        unsanitized_filename = file.filename
        filename = os.path.basename(unsanitized_filename)

        # replace filename with uuid
        id = str(uuid.uuid4())
        name = filename
        filename = f"{id}_{filename}"

        # llens(#52): 受け入れゲート(Attachment 前=保存前に server-side 強制)。
        # 拡張子 whitelist(空=全許可)と上限サイズ(MB)を突き合わせて拒否する。
        ext = name.rsplit(".", 1)[-1].lower() if "." in name else ""
        allowed_exts = request.app.state.config.ATTACHMENT_ALLOWED_EXTENSIONS
        if allowed_exts and ext not in allowed_exts:
            raise HTTPException(
                status_code=status.HTTP_400_BAD_REQUEST,
                detail=f"許可されていないファイル形式です(.{ext or '拡張子なし'})。",
            )
        max_size = request.app.state.config.ATTACHMENT_MAX_SIZE  # MB
        if max_size and file.size and file.size > max_size * 1024 * 1024:
            raise HTTPException(
                status_code=status.HTTP_400_BAD_REQUEST,
                detail=f"ファイルサイズが上限({max_size}MB)を超えています。",
            )

        contents, file_path = Storage.upload_file(file.file, filename)

        file_item = Files.insert_new_file(
            user.id,
            FileForm(
                **{
                    "id": id,
                    "filename": name,
                    "path": file_path,
                    "meta": {
                        "name": name,
                        "content_type": file.content_type,
                        "size": len(contents),
                        "data": file_metadata,
                    },
                }
            ),
        )
        if process:
            try:
                # llens(#52): テキスト化は Attachment Function に委譲(完全 opt-in)。
                # 現在のチャットのモデル(model_id)の meta.attachmentIds に割り当てられた
                # フックだけが発火し、file.data.content を埋める。model 無/未割り当ては何もしない。
                assigned_ids = None
                if model_id:
                    model = Models.get_model_by_id(model_id)
                    if model and model.meta:
                        assigned_ids = (model.meta.model_dump() or {}).get(
                            "attachmentIds"
                        )
                await process_attachment_functions(
                    request, file_item, user, assigned_ids
                )
                file_item = Files.get_file_by_id(id=id)
            except Exception as e:
                log.exception(e)
                log.error(f"Error processing file: {file_item.id}")
                file_item = FileModelResponse(
                    **{
                        **file_item.model_dump(),
                        "error": str(e.detail) if hasattr(e, "detail") else str(e),
                    }
                )

        if file_item:
            return file_item
        else:
            raise HTTPException(
                status_code=status.HTTP_400_BAD_REQUEST,
                detail=ERROR_MESSAGES.DEFAULT("Error uploading file"),
            )

    except HTTPException:
        # 受け入れゲート等の明示的な HTTPException は detail を保って伝播させる。
        raise
    except Exception as e:
        log.exception(e)
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=ERROR_MESSAGES.DEFAULT(e),
        )


